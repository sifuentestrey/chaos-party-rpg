const baseline=JSON.parse(fs.readFileSync(new URL('./fixtures/campaign-text-baseline.json',import.meta.url),'utf8'));
const catalog=()=>JSON.parse(fs.readFileSync(CAMPAIGN_TEXT_SOURCE,'utf8'));
const digest=value=>createHash('sha256').update(JSON.stringify(value)).digest('hex');
function behavior(state){
  const copy=structuredClone(state);
  for(const location of Object.values(copy.locations))if(location.id.startsWith('wild-'))location.name='[wild location display name]';
  for(const region of Object.values(copy.regions)){region.rumor='[region rumor]';region.quest.title='[quest title]';}
  // Preserve history structure and all other prose; mask only the exact display-name echo.
  for(const entry of copy.campaign.history)if(entry.type==='discovery'&&entry.location?.startsWith('wild-')&&entry.text===`Discovered ${state.locations[entry.location].name}.`)entry.text='Discovered [wild location display name].';
  return copy;
}
function sample(seed,api=campaign){
  const room=createRoom({code:'CONTENT',seed,now:0}),state=ensureItems(room);
  if(api!==campaign){delete state.locations['wild-0-0'];api.describeRegion(state,'wild-0-0');}
  for(const id of baseline.regionIds)api.enterRegion(room,state,id);
  return {room,state};
}
function assertSample({room,state},old,text){
  assert.equal(room.seed,old.authoritativeSeed);assert.equal(state.nextId,old.nextItemId);
  assert.equal(digest(behavior(state)),old.behaviorSha256,'non-configurable world state or RNG ordering changed');
  for(const region of old.regions){
    const actual=state.regions[region.id],location=state.locations[region.id];
    assert.equal(actual.quest.title,text.questTitles[actual.quest.kind]);
    assert.equal(actual.rumor,text.rumors[baseline.catalog.rumors.indexOf(region.rumor)]);
    if(region.id.startsWith('wild-')){
      const index=baseline.catalog.locationPrefixes.findIndex(prefix=>region.name.startsWith(prefix+' '));
      assert.ok(index>=0);assert.equal(location.name,text.locationPrefixes[index]+region.name.slice(baseline.catalog.locationPrefixes[index].length));
    }else assert.equal(location.name,region.name);
  }
}

