test('generator is reproducible and invalid JSON or schema never overwrites a previous artifact',()=>{
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'chaos-campaign-text-')),input=path.join(dir,'input.json'),output=path.join(dir,'output.js');
  try{
    fs.writeFileSync(input,JSON.stringify(baseline.catalog));assert.equal(buildCampaignText({input,output}).changed,true);
    const original=fs.readFileSync(output,'utf8');assert.equal(buildCampaignText({input,output}).changed,false);
    const reordered={questTitles:{restore:baseline.catalog.questTitles.restore,rescue:baseline.catalog.questTitles.rescue,recover:baseline.catalog.questTitles.recover},rumors:baseline.catalog.rumors,locationPrefixes:baseline.catalog.locationPrefixes};
    fs.writeFileSync(input,JSON.stringify(reordered,null,4));assert.equal(buildCampaignText({input,output}).changed,false);
    for(const invalid of ['{bad JSON',JSON.stringify({...baseline.catalog,reward:100}),JSON.stringify({...baseline.catalog,rumors:['wrong count']})]){
      fs.writeFileSync(input,invalid);assert.throws(()=>buildCampaignText({input,output}));assert.equal(fs.readFileSync(output,'utf8'),original);
      assert.deepEqual(fs.readdirSync(dir).sort(),['input.json','output.js']);
    }
    const absent=path.join(dir,'absent','output.js');assert.throws(()=>buildCampaignText({input,output:absent}));assert.equal(fs.existsSync(path.dirname(absent)),false);
    assert.throws(()=>buildCampaignText({input,output:input}));
  }finally{fs.rmSync(dir,{recursive:true,force:true});}
});
